function wordCount() {
	return blocks.reduce((sum, block) => {
		if (block.kind !== "p") return sum;
		return sum + block.text.split(/\s+/).filter(Boolean).length;
	}, 0);
}
function plateCount() {
	return blocks.filter((block) => block.kind === "plate").length;
}
function minutesToNextPlate(anchor) {
	let words = 0;
	for (let index = anchor; index < blocks.length; index++) {
		const block = blocks[index];
		if (!block) continue;
		if (index !== anchor && block.kind === "plate") break;
		if (block.kind === "p") words += block.text.split(/\s+/).filter(Boolean).length;
	}
	return Math.max(1, Math.round(words / 220));
}
function nearestPlate(anchor) {
	for (let index = anchor; index >= 0; index--) {
		const block = blocks[index];
		if (block?.kind === "plate") return block;
	}
	const first = blocks.find((block) => block.kind === "plate");
	return first && first.kind === "plate" ? first : null;
}
function pageText(pageBlocks) {
	return pageBlocks.map((block) => {
		if (block.kind === "p") return block.text;
		if (block.kind === "chapter") return block.title;
		if (block.kind === "plate") return block.caption;
		return "";
	}).filter(Boolean).join(" ");
}
var voiceToken = 0;
var clip = null;
var clipTimer = 0;
var speechRate = 1;
function findCue(chapters, text) {
	const wanted = text.replace(/\s+/g, " ").trim();
	for (const chapter of chapters) {
		const line = chapter.lines.find((item) => item.text.replace(/\s+/g, " ").trim() === wanted);
		if (line) return line.at;
	}
	return null;
}
function place(bookAudio, time) {
	let title = bookAudio.chapters[0]?.title ?? "Playing";
	let start = 0;
	for (const chapter of bookAudio.chapters) {
		const at = chapter.lines[0]?.at ?? 0;
		if (time + .05 >= at) {
			title = chapter.title;
			start = at;
		}
	}
	return {
		title,
		at: Math.max(0, time - start)
	};
}
function clock(seconds) {
	const total = Math.max(0, Math.floor(seconds));
	return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, "0")}`;
}
function spokenFrom(source, index) {
	for (let cursor = Math.max(0, index); cursor < source.length; cursor++) {
		const block = source[cursor];
		if (block?.kind === "p") return block.text;
		if (block?.kind === "chapter") return block.title;
	}
}
function setSpeechRate(rate) {
	speechRate = rate;
	if (clip) clip.playbackRate = rate;
}
async function playAudiobook(bookId, fromText, rate = 1, onNote) {
	stopSpeech();
	speechRate = rate;
	const mine = voiceToken;
	const recorded = audiobooks[bookId];
	if (!recorded || typeof Audio === "undefined") return "This book isn’t recorded yet";
	const startAt = fromText ? findCue(recorded.chapters, fromText) ?? 0 : 0;
	const audio = new Audio(recorded.src);
	audio.preload = "auto";
	audio.volume = 1;
	audio.setAttribute("playsinline", "true");
	audio.playbackRate = speechRate;
	clip = audio;
	const seek = () => {
		if (mine !== voiceToken) return;
		if (startAt > .2 && Number.isFinite(audio.duration) && startAt < audio.duration - .25) audio.currentTime = startAt;
	};
	audio.addEventListener("loadedmetadata", seek, { once: true });
	try {
		const started = audio.play();
		if (audio.readyState >= 1) seek();
		await started;
	} catch (error) {
		return error instanceof Error ? error.message : "Voice did not start";
	}
	if (mine !== voiceToken) return "Stopped";
	const note = () => {
		const here = place(recorded, audio.currentTime || startAt);
		onNote?.(`${here.title} · ${clock(here.at)}`);
	};
	note();
	const timer = window.setInterval(() => {
		if (mine !== voiceToken) return;
		note();
	}, 250);
	clipTimer = timer;
	await new Promise((resolve) => {
		audio.onended = () => resolve();
		audio.onerror = () => resolve();
	});
	window.clearInterval(timer);
	return mine === voiceToken ? true : "Stopped";
}
function stopSpeech() {
	voiceToken += 1;
	window.clearInterval(clipTimer);
	if (clip) {
		clip.pause();
		clip.src = "";
		clip = null;
	}
}
